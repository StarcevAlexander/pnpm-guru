use crate::manifest::PackageManifest;
use crate::store::ContentStore;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug)]
pub enum AssembleError {
    MissingStoreFile { hash: String, path: String },
    IntegrityMismatch { hash: String, path: String },
    Io(std::io::Error),
}

impl std::fmt::Display for AssembleError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AssembleError::MissingStoreFile { hash, .. } => write!(f, "store file {hash} missing"),
            AssembleError::IntegrityMismatch { hash, .. } => {
                write!(f, "integrity mismatch for {hash}")
            }
            AssembleError::Io(e) => write!(f, "io error: {e}"),
        }
    }
}

impl std::error::Error for AssembleError {}

impl From<std::io::Error> for AssembleError {
    fn from(e: std::io::Error) -> Self {
        AssembleError::Io(e)
    }
}

impl From<crate::store::StoreError> for AssembleError {
    fn from(e: crate::store::StoreError) -> Self {
        match e {
            crate::store::StoreError::IntegrityMismatch { expected, .. } => {
                AssembleError::IntegrityMismatch {
                    hash: expected,
                    path: String::from("<store>"),
                }
            }
            other => AssembleError::Io(std::io::Error::other(other.to_string())),
        }
    }
}

fn symlink_or_copy_dir(source: &Path, target: &Path) -> std::io::Result<bool> {
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(source, target).map(|_| true)
    }
    #[cfg(windows)]
    {
        match std::os::windows::fs::symlink_dir(source, target) {
            Ok(()) => Ok(true),
            Err(_) => {
                copy_dir_recursive(source, target)?;
                Ok(false)
            }
        }
    }
}

#[allow(dead_code)]
fn copy_dir_recursive(source: &Path, target: &Path) -> std::io::Result<()> {
    fs::create_dir_all(target)?;
    for entry in fs::read_dir(source)? {
        let entry = entry?;
        let entry_target = target.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_dir_recursive(&entry.path(), &entry_target)?;
        } else {
            let _ = fs::copy(entry.path(), &entry_target);
        }
    }
    Ok(())
}

pub struct AssembledPackage {
    pub real_dir: PathBuf,
    pub alias_dir: PathBuf,
    pub files_linked: usize,
    pub alias_was_symlink: bool,
}

pub fn assemble(
    store: &ContentStore,
    manifest: &PackageManifest,
    target_root: &Path,
) -> Result<AssembledPackage, AssembleError> {
    let real_dir = target_root
        .join(".pnpm")
        .join(format!("{}@{}", manifest.name, manifest.version))
        .join("node_modules")
        .join(&manifest.name);

    fs::create_dir_all(&real_dir)?;
    let mut files_linked = 0usize;

    for file in &manifest.files {
        let data = store.read(&file.hash).map_err(|e| match e {
            crate::store::StoreError::IntegrityMismatch { expected, .. } => {
                AssembleError::IntegrityMismatch {
                    hash: expected.clone(),
                    path: file.path.clone(),
                }
            }
            _other => AssembleError::MissingStoreFile {
                hash: file.hash.clone(),
                path: file.path.clone(),
            },
        })?;
        let target = real_dir.join(&file.path);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&target, &data)?;
        files_linked += 1;
    }

    let alias = target_root.join(&manifest.name);
    if alias.exists() {
        let _ = fs::remove_dir_all(&alias);
    }
    let alias_was_symlink = symlink_or_copy_dir(&real_dir, &alias)?;

    Ok(AssembledPackage {
        real_dir,
        alias_dir: alias,
        files_linked,
        alias_was_symlink,
    })
}
